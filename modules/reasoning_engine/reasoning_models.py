"""
Reasoning Models Module
Defines classical Artificial Intelligence data structures for:
1. Fact (Original vs Inferred with SPO representation)
2. InferenceRule (Logical implication with Premises -> Conclusion)
3. InferenceTrace (Step-by-step reasoning derivation audit)
4. ReasoningResult (Outcome of an inference cycle)

ACADEMIC EXPLANATION:
In Symbolic Artificial Intelligence, knowledge is stored as explicit facts
(propositions) and general rules (Horn clauses / IF-THEN rules).
Inferred facts are newly deduced knowledge items derived through formal
inference (e.g. Modus Ponens).
"""

from dataclasses import dataclass, field, asdict
from typing import Optional, List, Dict, Any, Tuple, Union


@dataclass(frozen=True)
class Fact:
    """
    Represents an atomic proposition in the reasoning engine as a
    Subject-Predicate-Object (SPO) triple.
    
    Attributes:
        subject: The entity being described (e.g. 'Bangalore', 'Python').
        predicate: The relationship or property (e.g. 'capital of', 'is a').
        object: The target entity, category, or value (e.g. 'Karnataka', 'programming language').
        fact_type: 'original' (from source document) or 'inferred' (deduced by rules).
        fact_id: Unique identifier (integer from SQLite if original, string like 'inf_1' if inferred).
        document_id: Optional source document reference (for provenance tracking).
        source_sentence: Verbatim source sentence where the fact was stated.
        sentence_index: 0-based sentence position within the document.
    """
    subject: str
    predicate: str
    object: str
    fact_type: str = 'original'                     # 'original' or 'inferred'
    fact_id: Optional[Union[int, str]] = None
    document_id: Optional[int] = None
    source_sentence: Optional[str] = None
    sentence_index: Optional[int] = None

    def __post_init__(self):
        # Normalize fact_type to lowercase in frozen instance
        norm_type = self.fact_type.lower()
        if norm_type not in ('original', 'inferred'):
            raise ValueError(f"Invalid fact_type '{self.fact_type}'. Must be 'original' or 'inferred'.")
        object.__setattr__(self, 'fact_type', norm_type)

    @property
    def triple(self) -> Tuple[str, str, str]:
        """Returns the canonical (Subject, Predicate, Object) tuple."""
        return (self.subject, self.predicate, self.object)

    @property
    def normalized_key(self) -> Tuple[str, str, str]:
        """Case-folded SPO key for case-insensitive duplicate prevention."""
        return (self.subject.strip().lower(),
                self.predicate.strip().lower(),
                self.object.strip().lower())

    @property
    def is_inferred(self) -> bool:
        """Helper to quickly check if this fact was derived by reasoning."""
        return self.fact_type == 'inferred'

    @property
    def is_original(self) -> bool:
        """Helper to check if this fact is a direct ground observation."""
        return self.fact_type == 'original'

    def to_dict(self) -> Dict[str, Any]:
        """Serialize fact object to dictionary."""
        return asdict(self)

    def __repr__(self) -> str:
        tag = "ORIGINAL" if self.is_original else "INFERRED"
        return (f"<Fact [{tag}] #{self.fact_id or '?'} "
                f"({self.subject} -[{self.predicate}]-> {self.object})>")


@dataclass
class InferenceRule:
    """
    Represents an IF-THEN logical inference rule (production rule).
    
    Structure:
        IF (Premise 1 AND Premise 2 AND ...)
        THEN (Conclusion)
        
    Attributes:
        rule_id: Unique rule identifier (e.g. 'R1_CAPITAL_LOCATION').
        rule_name: Human-readable rule title.
        premises: List of premise patterns (tuples or conditions) required to fire.
        conclusion: The resulting fact pattern derived when all premises are satisfied.
        description: Natural language explanation of the logical principle.
    """
    rule_id: str
    rule_name: str
    premises: List[Any]
    conclusion: Any
    description: str = ""

    def to_dict(self) -> Dict[str, Any]:
        """Serialize inference rule to dictionary."""
        return asdict(self)

    def __repr__(self) -> str:
        return f"<InferenceRule {self.rule_id}: {self.rule_name}>"


@dataclass
class InferenceTrace:
    """
    Provides an audit trail explaining how an inferred fact was derived.
    Essential for classical Artificial Intelligence explainability.
    
    Attributes:
        derived_fact: The new Fact object generated by the rule.
        applied_rule_id: The ID of the InferenceRule that fired.
        supporting_fact_ids: List of fact IDs that satisfied the rule's premises.
        reasoning_method: The inference algorithm used ('forward_chaining' or 'backward_chaining').
        explanation: Human-readable explanation of the reasoning step.
    """
    derived_fact: Fact
    applied_rule_id: str
    supporting_fact_ids: List[Union[int, str]]
    reasoning_method: str = 'forward_chaining'      # 'forward_chaining' or 'backward_chaining'
    explanation: Optional[str] = None

    def to_dict(self) -> Dict[str, Any]:
        """Serialize inference trace to dictionary."""
        return {
            'derived_fact': self.derived_fact.to_dict(),
            'applied_rule_id': self.applied_rule_id,
            'supporting_fact_ids': list(self.supporting_fact_ids),
            'reasoning_method': self.reasoning_method,
            'explanation': self.explanation
        }

    def __repr__(self) -> str:
        return (f"<InferenceTrace: Rule {self.applied_rule_id} -> "
                f"Derived Fact #{self.derived_fact.fact_id} via {self.reasoning_method}>")


@dataclass
class ReasoningResult:
    """
    Structured outcome of an inference execution cycle.
    
    Attributes:
        status: 'success' (inference succeeded), 'no_inference' (no new facts derived), or 'error'.
        original_facts: Ground facts loaded into working memory.
        inferred_facts: New facts deduced by applying inference rules.
        inference_traces: Detailed trace of every rule firing and supporting facts.
        explanation: High-level summary of the deduction process.
    """
    status: str = 'success'                         # 'success', 'no_inference', 'error'
    original_facts: List[Fact] = field(default_factory=list)
    inferred_facts: List[Fact] = field(default_factory=list)
    inference_traces: List[InferenceTrace] = field(default_factory=list)
    explanation: Optional[str] = None

    @property
    def total_facts_count(self) -> int:
        """Total count of facts (original + inferred)."""
        return len(self.original_facts) + len(self.inferred_facts)

    @property
    def inferred_facts_count(self) -> int:
        """Count of newly deduced facts."""
        return len(self.inferred_facts)

    def to_dict(self) -> Dict[str, Any]:
        """Convert complete reasoning outcome to a serializable dictionary."""
        return {
            'status': self.status,
            'original_facts_count': len(self.original_facts),
            'inferred_facts_count': len(self.inferred_facts),
            'total_facts_count': self.total_facts_count,
            'original_facts': [f.to_dict() for f in self.original_facts],
            'inferred_facts': [f.to_dict() for f in self.inferred_facts],
            'inference_traces': [t.to_dict() for t in self.inference_traces],
            'explanation': self.explanation
        }

    def __repr__(self) -> str:
        return (f"<ReasoningResult status='{self.status}' "
                f"original={len(self.original_facts)} inferred={len(self.inferred_facts)}>")
