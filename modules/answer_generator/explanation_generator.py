"""
Explanation Generator Module
Produces deterministic, structured, human-readable explanations for answers
generated by the DocuMind AI Question Answering System.

ACADEMIC EXPLANATION:
In Symbolic Artificial Intelligence and Expert Systems, explanation generation
(Explainable AI / XAI) provides transparent, auditable rationales for system conclusions:
1. Ground Evidence: Explaining which factual assertions in the Knowledge Base support the answer.
2. Inference Chains: Reconstructing the step-by-step deduction path (Modus Ponens / SLD resolution)
   including rule IDs, rule names, premise-to-conclusion derivations, and intermediate subgoals.
3. Provenance Tracking: Linking each ground fact back to its source document ID and sentence text.
4. Epistemic Humility: Under the Open-World Assumption (OWA), clearly distinguishing between
   unrecorded knowledge (unknown) and unsupported queries, without fabricating negations or facts.

ACADEMIC COMPLIANCE:
- Strictly rule-based, deterministic formatting using declarative templates.
- Zero NLP libraries (no spaCy, no NLTK, no transformer models).
- Zero LLMs, generative AI, RAG embeddings, or semantic similarity.
- Zero fabricated citations, rule steps, or source records.
"""

from typing import List, Dict, Any, Optional, Union, Tuple
from modules.question_processor.query_models import StructuredQuery, RetrievalResult
from modules.question_processor.parser import QuestionParser
from modules.reasoning_engine.reasoning_models import (
    Fact as ReasoningFact,
    ReasoningResult,
    InferenceTrace,
    InferenceRule,
)
from modules.reasoning_engine.backward_chaining import ProofResult
from modules.reasoning_engine.rule_base import get_rule_by_id, ALL_RULES
from .answer_models import AnswerResponse
from .generator import AnswerGenerator, RULE_DISPLAY_NAMES


class ExplanationGenerator:
    """
    Deterministic explanation generator for DocuMind AI.
    Translates factual retrieval and symbolic inference traces into
    transparent, evidence-backed natural language explanations.
    """

    def __init__(self):
        self.parser = QuestionParser()
        self.answer_generator = AnswerGenerator()

    def generate_explanation(self,
                             answer_response: Optional[AnswerResponse] = None,
                             query: Optional[Union[str, StructuredQuery]] = None,
                             retrieval_result: Optional[RetrievalResult] = None,
                             reasoning_result: Optional[Union[ReasoningResult, ProofResult]] = None,
                             **kwargs) -> str:
        """
        Produce a clear, deterministic, human-readable explanation for an answer.

        Accepts either:
        1. An existing AnswerResponse object.
        2. Query, retrieval_result, and reasoning_result inputs directly.
        3. A combination of both (enriching AnswerResponse with deeper reasoning traces).

        Returns:
            A comprehensive, human-readable explanation string detailing facts,
            inference rules, deduction steps, and source provenance.
        """
        # 1. Handle completely empty input
        if answer_response is None and query is None and retrieval_result is None and reasoning_result is None:
            return "Incomplete input: No query, answer response, or reasoning result was provided for explanation generation."

        # 2. Reconstruct AnswerResponse if not supplied
        if answer_response is None:
            if query is None:
                # Synthesize a fallback query if retrieval_result has one
                if retrieval_result and hasattr(retrieval_result, 'query'):
                    query = retrieval_result.query
                else:
                    query = "Unknown query"
            answer_response = self.answer_generator.generate_answer(
                query=query,
                retrieval_result=retrieval_result,
                reasoning_result=reasoning_result
            )

        # 3. Extract and normalize parsed query
        structured_query: Optional[StructuredQuery] = None
        if isinstance(query, StructuredQuery):
            structured_query = query
        elif isinstance(query, str):
            structured_query = self.parser.parse(query)
        elif retrieval_result and hasattr(retrieval_result, 'query') and isinstance(retrieval_result.query, StructuredQuery):
            structured_query = retrieval_result.query

        # 4. Route to specialized explanation builders based on answer status and type
        status = answer_response.answer_status
        ans_type = answer_response.answer_type

        # Case F: Unsupported Questions
        if status == 'unsupported':
            return self._explain_unsupported_question(answer_response, structured_query)

        # Case E: Unknown Answers
        if status == 'unknown':
            return self._explain_unknown_answer(answer_response, structured_query)

        # Error status
        if status == 'error':
            return self._explain_error_status(answer_response)

        # Check for Conflicting facts in answer text
        if "Conflicting information found in the knowledge base:" in answer_response.answer_text:
            return self._explain_conflicting_facts(answer_response)

        # Check for Boolean answer
        is_boolean = False
        if structured_query and structured_query.expected_answer_field == 'boolean':
            is_boolean = True
        elif answer_response.answer_text.startswith("Yes, "):
            is_boolean = True

        # Case B: Inferred answers
        if ans_type in ('inferred', 'mixed') or answer_response.applied_rule_ids:
            return self._explain_inferred_answer(
                answer_response=answer_response,
                reasoning_result=reasoning_result,
                structured_query=structured_query,
                is_boolean=is_boolean
            )

        # Case A & D: Direct factual answers (single or multiple)
        return self._explain_direct_answer(
            answer_response=answer_response,
            structured_query=structured_query,
            is_boolean=is_boolean
        )

    # Alias for convenience
    explain = generate_explanation

    # ==========================================================================
    # Specialized Explanation Synthesizers
    # ==========================================================================

    def _explain_unsupported_question(self,
                                      answer_response: AnswerResponse,
                                      query: Optional[StructuredQuery]) -> str:
        """Explain why an unsupported question cannot be answered."""
        ans = answer_response
        lines = [
            "Explanation: Unsupported Question Format.",
            "- Status: The question could not be processed because its syntactic structure or relation type is not supported by DocuMind AI's deterministic factual grammar.",
            "- Preserved Query: \"" + ans.original_question + "\"",
            "- Supported Relation Categories: Capital, Location, Establishment, Creator/Author, Part-Whole, Border/Adjacency, Production, Identity, and Classification.",
            "- Integrity Guarantee: In compliance with classical symbolic AI constraints, no answer, rule, or source citation has been fabricated."
        ]
        if query and query.error_message:
            lines.insert(2, f"- Parser Note: {query.error_message}")
        return "\n".join(lines)

    def _explain_unknown_answer(self,
                                answer_response: AnswerResponse,
                                query: Optional[StructuredQuery]) -> str:
        """Explain why an answer is unknown under the Open-World Assumption."""
        ans = answer_response
        is_boolean = (query and query.expected_answer_field == 'boolean') or (
            ans.original_question.lower().startswith(('is ', 'does ', 'did ', 'are ', 'was ', 'were '))
        )

        lines = [
            "Explanation: Knowledge Base Insufficiency.",
            f"- Status: No matching ground facts or valid deductive inference chains were found for \"{ans.original_question}\"."
        ]

        if is_boolean:
            lines.extend([
                "- Query Type: Boolean Verification.",
                "- Open-World Assumption (OWA): In classical logic, the absence of proof is not proof of negation. The system does not assume 'No' simply because the assertion is unrecorded.",
                "- Conclusion: The queried relationship is neither proven nor disproven; it is unrecorded in the knowledge base."
            ])
        else:
            lines.extend([
                "- Open-World Assumption (OWA): The knowledge base represents an incomplete record of world knowledge. The system reports 'unknown' rather than hallucinating an answer.",
                "- Supporting Evidence: 0 facts matched; 0 inference rules fired."
            ])

        return "\n".join(lines)

    def _explain_error_status(self, answer_response: AnswerResponse) -> str:
        """Explain an execution or input validation error."""
        ans = answer_response
        return (
            "Explanation: System Error.\n"
            f"- Error Detail: {ans.explanation or 'An unexpected error occurred during processing.'}\n"
            f"- Preserved Input: \"{ans.original_question}\""
        )

    def _explain_conflicting_facts(self, answer_response: AnswerResponse) -> str:
        """Explain contradictory factual records discovered in the knowledge base."""
        ans = answer_response
        lines = [
            "Explanation: Conflicting Information Detected.",
            "- Status: Multiple contradictory assertions were discovered in the knowledge base for a single-valued relation.",
            "- Contradictory Assertions:"
        ]

        # Extract facts from supporting_facts
        if ans.supporting_facts:
            for idx, f in enumerate(ans.supporting_facts, 1):
                fid = f.get('fact_id', '?')
                subj = f.get('subject', '')
                pred = f.get('predicate', '')
                obj = f.get('object', '')
                doc_id = f.get('document_id')
                sent = f.get('source_sentence')

                fact_desc = f"  {idx}. Fact #{fid}: ({subj}, {pred}, {obj})"
                if doc_id is not None or sent is not None:
                    src_str = f" [Source: Document #{doc_id if doc_id is not None else '?'}"
                    if sent:
                        src_str += f", \"{sent}\""
                    src_str += "]"
                    fact_desc += src_str
                else:
                    fact_desc += " [Source: Not recorded in knowledge base]"
                lines.append(fact_desc)
        else:
            lines.append("  - " + ans.answer_text)

        lines.extend([
            "- Resolution Policy: Deterministic symbolic AI systems do not guess or randomly pick one assertion over another.",
            "- Academic Integrity: Both assertions and their supporting Fact IDs are disclosed transparently to the user."
        ])
        return "\n".join(lines)

    def _explain_direct_answer(self,
                               answer_response: AnswerResponse,
                               structured_query: Optional[StructuredQuery],
                               is_boolean: bool) -> str:
        """Explain a direct ground factual answer."""
        ans = answer_response
        facts = ans.supporting_facts
        num_facts = len(facts)

        lines = [
            "Explanation: Direct Factual Retrieval.",
            f"- Question: \"{ans.original_question}\"",
            f"- Answer: \"{ans.answer_text}\"",
            "- Method: Direct lookup from the Knowledge Base without deductive rule execution."
        ]

        if is_boolean:
            lines.append("- Logic Mode: Boolean Verification confirmed via direct ground evidence.")

        # Supporting facts details
        if num_facts == 0:
            # Fallback if supporting_facts was not serialized but supporting_fact_ids exist
            if ans.supporting_fact_ids:
                lines.append(f"- Supporting Fact ID(s): {ans.supporting_fact_ids}")
            else:
                lines.append("- Supporting Evidence: Verified ground assertion (fact identifier unrecorded).")
        elif num_facts == 1:
            f = facts[0]
            fid = f.get('fact_id', '?')
            subj = f.get('subject', '')
            pred = f.get('predicate', '')
            obj = f.get('object', '')
            lines.append(f"- Supporting Ground Fact: Fact #{fid} ({subj}, {pred}, {obj})")
        else:
            # Case D: Multiple results
            lines.append(f"- Multiple Evidence Records ({num_facts} ground facts):")
            for idx, f in enumerate(facts, 1):
                fid = f.get('fact_id', '?')
                subj = f.get('subject', '')
                pred = f.get('predicate', '')
                obj = f.get('object', '')
                lines.append(f"  {idx}. Fact #{fid}: ({subj}, {pred}, {obj})")

        # Provenance details
        lines.append("- Source Provenance:")
        sources_to_use = list(ans.sources) if ans.sources else []
        if not sources_to_use and ans.supporting_facts:
            for sf in ans.supporting_facts:
                sources_to_use.append({
                    'document_id': sf.get('document_id'),
                    'source_sentence': sf.get('source_sentence'),
                    'fact_id': sf.get('fact_id'),
                    'filename': sf.get('filename')
                })

        if sources_to_use:
            for s in sources_to_use:
                doc_id = s.get('document_id')
                sent = s.get('source_sentence')
                fid = s.get('fact_id')
                fid_tag = f" (Fact #{fid})" if fid else ""
                filename = s.get('filename')

                if doc_id is not None or sent is not None:
                    doc_str = f"Document #{doc_id}" if doc_id is not None else "Document unrecorded"
                    if filename and not str(filename).startswith("Document #"):
                        doc_str += f" ({filename})"
                    sent_str = f": \"{sent}\"" if sent else ""
                    lines.append(f"  - {doc_str}{sent_str}{fid_tag}")
                else:
                    lines.append(f"  - Source document reference: Not recorded in knowledge base{fid_tag}.")
        else:
            lines.append("  - Source document reference: Not recorded in knowledge base.")

        return "\n".join(lines)

    def _explain_inferred_answer(self,
                                 answer_response: AnswerResponse,
                                 reasoning_result: Optional[Union[ReasoningResult, ProofResult]],
                                 structured_query: Optional[StructuredQuery],
                                 is_boolean: bool) -> str:
        """Explain an inferred answer step-by-step with rule details and provenance."""
        applied_rules = answer_response.applied_rule_ids
        supp_fact_ids = answer_response.supporting_fact_ids

        lines = [
            "Explanation: Symbolic Deductive Inference.",
            f"- Question: \"{answer_response.original_question}\"",
            f"- Answer: \"{answer_response.answer_text}\"",
            "- Method: Multi-hop symbolic reasoning using deductive production rules."
        ]

        if is_boolean:
            lines.append("- Logic Mode: Boolean proposition deductively proven from verified premises.")

        # Applied rules description
        lines.append("- Applied Inference Rule(s):")
        for r_id in applied_rules:
            rule_obj = get_rule_by_id(r_id)
            if rule_obj:
                lines.append(f"  - Rule {rule_obj.rule_id} ({rule_obj.rule_name}): {rule_obj.description}")
            else:
                friendly_name = RULE_DISPLAY_NAMES.get(r_id, r_id)
                lines.append(f"  - Rule {r_id} ({friendly_name})")

        # Step-by-step reasoning derivation
        traces: List[InferenceTrace] = []
        if reasoning_result and hasattr(reasoning_result, 'inference_traces'):
            traces = list(reasoning_result.inference_traces)

        if traces:
            lines.append("- Step-by-Step Reasoning Chain:")
            for idx, trace in enumerate(traces, 1):
                rule_id = trace.applied_rule_id
                rule_name = RULE_DISPLAY_NAMES.get(rule_id, rule_id)
                supp_ids = trace.supporting_fact_ids
                df = trace.derived_fact
                derived_str = f"({df.subject}, {df.predicate}, {df.object})" if df else "target goal"
                df_id = getattr(df, 'fact_id', 'new')

                step_line = (
                    f"  Step {idx}: Applied Rule {rule_id} ({rule_name}) "
                    f"using premise fact(s) {supp_ids} -> Derived Fact #{df_id}: {derived_str}."
                )
                lines.append(step_line)
        else:
            # If granular traces are omitted, construct a formal logical synthesis from available metadata
            lines.append("- Step-by-Step Reasoning Chain:")
            rules_str = ", ".join(applied_rules) if applied_rules else "deductive rules"
            facts_str = f"supporting facts {supp_fact_ids}" if supp_fact_ids else "available working memory assertions"
            lines.append(f"  Step 1: Ground premises from {facts_str} unified with Rule {rules_str} to establish the final conclusion.")

        # Supporting ground facts
        lines.append(f"- Ground Premise Fact IDs: {supp_fact_ids if supp_fact_ids else 'Unrecorded'}")

        # Provenance / Sources
        lines.append("- Source Provenance:")
        sources_to_use = list(answer_response.sources) if answer_response.sources else []
        if not sources_to_use and answer_response.supporting_facts:
            for sf in answer_response.supporting_facts:
                sources_to_use.append({
                    'document_id': sf.get('document_id'),
                    'source_sentence': sf.get('source_sentence'),
                    'fact_id': sf.get('fact_id'),
                    'filename': sf.get('filename')
                })

        if sources_to_use:
            for s in sources_to_use:
                doc_id = s.get('document_id')
                sent = s.get('source_sentence')
                fid = s.get('fact_id')
                fid_tag = f" (Fact #{fid})" if fid else ""
                filename = s.get('filename')

                if doc_id is not None or sent is not None:
                    doc_str = f"Document #{doc_id}" if doc_id is not None else "Document unrecorded"
                    if filename and not str(filename).startswith("Document #"):
                        doc_str += f" ({filename})"
                    sent_str = f": \"{sent}\"" if sent else ""
                    lines.append(f"  - {doc_str}{sent_str}{fid_tag}")
                else:
                    lines.append(f"  - Source document reference: Not recorded in knowledge base{fid_tag}.")
        else:
            lines.append("  - Source document reference: Not recorded in knowledge base.")

        return "\n".join(lines)

    # ==========================================================================
    # Structured Dictionary Representation for Auditing
    # ==========================================================================

    def generate_detailed_explanation(self,
                                      answer_response: Optional[AnswerResponse] = None,
                                      query: Optional[Union[str, StructuredQuery]] = None,
                                      retrieval_result: Optional[RetrievalResult] = None,
                                      reasoning_result: Optional[Union[ReasoningResult, ProofResult]] = None,
                                      **kwargs) -> Dict[str, Any]:
        """
        Produce a structured dictionary audit of the explanation for grading and debugging.
        """
        explanation_text = self.generate_explanation(
            answer_response=answer_response,
            query=query,
            retrieval_result=retrieval_result,
            reasoning_result=reasoning_result,
            **kwargs
        )

        ans = answer_response
        if ans is None:
            ans = self.answer_generator.generate_answer(
                query=query or "Unknown query",
                retrieval_result=retrieval_result,
                reasoning_result=reasoning_result
            )

        return {
            'original_question': ans.original_question,
            'answer_text': ans.answer_text,
            'answer_status': ans.answer_status,
            'answer_type': ans.answer_type,
            'confidence': ans.confidence,
            'supporting_fact_ids': list(ans.supporting_fact_ids),
            'applied_rule_ids': list(ans.applied_rule_ids),
            'sources': list(ans.sources),
            'explanation_text': explanation_text
        }


# ==============================================================================
# Public Module-Level Convenience Function
# ==============================================================================

def generate_explanation(answer_response: Optional[AnswerResponse] = None,
                         query: Optional[Union[str, StructuredQuery]] = None,
                         retrieval_result: Optional[RetrievalResult] = None,
                         reasoning_result: Optional[Union[ReasoningResult, ProofResult]] = None,
                         **kwargs) -> str:
    """
    Convenience function to generate a human-readable explanation for an answer.
    """
    generator = ExplanationGenerator()
    return generator.generate_explanation(
        answer_response=answer_response,
        query=query,
        retrieval_result=retrieval_result,
        reasoning_result=reasoning_result,
        **kwargs
    )
